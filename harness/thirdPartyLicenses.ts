import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";

// THIRD_PARTY_LICENSES lists every third-party package whose code the built
// page carries, with its licence text, so the bundle can drop the licence
// comments minification would otherwise keep (vite.config.ts copies the file
// into dist/). The packages are package.json's dependencies and what they
// depend on, as package-lock.json resolves them, the workbox modules
// vite-plugin-pwa builds into the page and its service worker, and the files
// vendored under src/vendor/.

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const LICENSES_FILE = join(ROOT, "THIRD_PARTY_LICENSES");

/**
 * vite-plugin-pwa is a dev dependency, but these workbox modules end up in
 * dist/: workbox-window in the page (src/ui/UpdateNotice.tsx registers the
 * worker with it) and precaching and routing in the generated sw.js.
 */
const PWA_RUNTIME = ["workbox-window", "workbox-precaching", "workbox-routing"];
/** Packages of type declarations only: nothing of theirs reaches the bundle. */
const TYPES_ONLY = /^@types\//;
const LICENSE_FILE_NAMES = /^(licen[cs]e|copying)(\.(md|txt))?$/i;

interface Vendored {
  name: string;
  source: string;
  licence: string;
  licenceFile: string;
}

const VENDORED: Vendored[] = [
  {
    name: "Rom Patcher JS (src/vendor/rompatcher/)",
    source: "https://github.com/marcrobledo/RomPatcher.js at commit 3183884086825c3a57c72026234debcef1e2240c",
    licence: "MIT",
    licenceFile: "src/vendor/rompatcher/LICENSE",
  },
];

interface LockEntry {
  version?: string;
  license?: string;
  dependencies?: Record<string, string>;
  dev?: boolean;
}

interface Package {
  name: string;
  version: string;
  licence: string;
  path: string;
}

/** The lock path a dependency of `from` resolves to: Node's lookup, nearest node_modules first. */
function resolveInLock(packages: Record<string, LockEntry>, from: string, name: string): string {
  let base = from;
  for (;;) {
    const candidate = posix.join(base, "node_modules", name);
    if (packages[candidate]) return candidate;
    if (base === "") throw new Error(`${name}, needed by ${from || "package.json"}, is not in package-lock.json.`);
    const parent = base.lastIndexOf("node_modules/");
    base = parent <= 0 ? "" : base.slice(0, parent - 1);
  }
}

/** The packages the built page carries, by lock path, each once, sorted by name. */
export function bundledPackages(root = ROOT): Package[] {
  const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as { dependencies?: Record<string, string> };
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8")) as { packages: Record<string, LockEntry> };
  const found = new Map<string, Package>();
  const visit = (from: string, name: string) => {
    if (TYPES_ONLY.test(name)) return;
    const path = resolveInLock(lock.packages, from, name);
    if (found.has(path)) return;
    const entry = lock.packages[path];
    if (!entry.version || !entry.license) throw new Error(`package-lock.json gives ${path} no version or licence.`);
    found.set(path, { name, version: entry.version, licence: entry.license, path });
    for (const dependency of Object.keys(entry.dependencies ?? {})) visit(path, dependency);
  };
  for (const name of [...Object.keys(manifest.dependencies ?? {}), ...PWA_RUNTIME]) visit("", name);
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function licenceText(root: string, folder: string): string {
  const file = readdirSync(join(root, folder)).find((name) => LICENSE_FILE_NAMES.test(name));
  if (!file) throw new Error(`${folder} has no LICENSE file to copy.`);
  return readFileSync(join(root, folder, file), "utf8").trim();
}

function section(title: string, details: string[], text: string): string {
  return [`${"=".repeat(78)}`, title, ...details, "", text, ""].join("\n");
}

/** The text of THIRD_PARTY_LICENSES as the dependencies installed under `root` give it. */
export function thirdPartyLicenses(root = ROOT): string {
  const header = [
    "Third-party software in retrowright's built page",
    "",
    "Generated by `npm run licenses` (harness/thirdPartyLicenses.ts) from",
    "package-lock.json and the licence files of the installed packages. The",
    "built page (dist/) carries this file as THIRD_PARTY_LICENSES.txt.",
    "",
  ].join("\n");
  const packages = bundledPackages(root).map((pkg) => section(`${pkg.name} ${pkg.version}`, [`Licence: ${pkg.licence}`], licenceText(root, pkg.path)));
  const vendored = VENDORED.map((item) => {
    if (!existsSync(join(root, item.licenceFile))) throw new Error(`${item.licenceFile} is missing.`);
    return section(item.name, [`Source: ${item.source}`, `Licence: ${item.licence}`], readFileSync(join(root, item.licenceFile), "utf8").trim());
  });
  return [header, ...packages, ...vendored].join("\n");
}
